% BUILD_STANDALONE  Builds the standalone program (runs without MATLAB) and its installer.
% Needs MATLAB Compiler. Put this file, CDA_launcher.m, Compressor_design_app.m,
% cda_core.m, cda_guide.html and Compressor_offdesign_app.m in one folder, cd there and run it.
% Users of the program install the free MATLAB Runtime of the SAME release (the installer
% built below downloads it automatically).
files = {'Compressor_design_app.m', 'cda_core.m', 'cda_guide.html', 'cda_offdesign_guide.html', 'Compressor_offdesign_app.m', 'CDA_icon_512.png', 'cda_configurations.png'};
missing = files(~cellfun(@(x) exist(x, 'file') > 0, files));
if ~isempty(missing), error('Missing in this folder: %s', strjoin(missing, ', ')); end
opts = compiler.build.StandaloneApplicationOptions('CDA_launcher.m', ...
    'ExecutableName', 'CDA_Compressor', ...
    'AdditionalFiles', files, ...
    'OutputDir', fullfile(pwd, 'build_standalone'), ...
    'ExecutableIcon', 'CDA_icon_512.png', ...
    'Verbose', 'on');

results = compiler.build.standaloneApplication(opts);
% installer (Windows .exe / macOS .app / Linux) that also installs the MATLAB Runtime from the web
compiler.package.installer(results, 'InstallerName', 'CDA_Compressor_Installer', ...
    'ApplicationName', 'CDA Compressor', 'AuthorName', 'Ahmed Hassan', 'Version', '1.0', ...
    'RuntimeDelivery', 'web', 'OutputDir', fullfile(pwd, 'installer'));
fprintf('Program:   %s\nInstaller: %s\n', fullfile(pwd, 'build_standalone'), fullfile(pwd, 'installer'));
